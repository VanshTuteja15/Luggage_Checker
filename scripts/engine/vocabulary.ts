/* ------------------------------------------------------------------ */
/*  npm run engine:vocab                                               */
/*                                                                     */
/*  v5 F2.2: writes src/lib/engine/query/vocabulary-base.ts, the       */
/*  snapshot of our catalogue's brands and lines that the eval and a   */
/*  freshly started server use. The running server rebuilds the same   */
/*  thing from the database after discovery (engine/server.ts); this   */
/*  file only makes the eval deterministic. Reads DATABASE_URL, writes  */
/*  nothing to it.                                                      */
/* ------------------------------------------------------------------ */

import { writeFileSync } from "node:fs";
import { vocabularyFromRows } from "../../src/lib/engine/query/vocabulary";
import { PgEngineStore } from "../../src/lib/engine/store/pg";

const OUT = "src/lib/engine/query/vocabulary-base.ts";

async function main(): Promise<void> {
  const url = process.env.DATABASE_URL;
  if (!url) throw new Error("DATABASE_URL is required (npm run db:dev -- up prints one)");
  const store = new PgEngineStore(url, 2);
  const rows = await store.vocabularyRows();
  const builtAt = new Date().toISOString().slice(0, 10);
  const v = vocabularyFromRows(rows, `${builtAt}T00:00:00.000Z`);
  const body = [
    "/* ------------------------------------------------------------------ */",
    "/*  GENERATED by `npm run engine:vocab` (scripts/engine/vocabulary.ts) */",
    `/*  from the catalogue on ${builtAt}. Do not edit by hand.                */`,
    "/*  Brands and product lines our stores list, with active listing     */",
    "/*  counts. Server-side and eval only (not bundled for the browser).  */",
    "/* ------------------------------------------------------------------ */",
    "",
    'import type { Vocabulary } from "./vocabulary";',
    "",
    "export const BASE_VOCABULARY: Vocabulary = {",
    `  builtAt: ${JSON.stringify(v.builtAt)},`,
    "  brands: [",
    ...v.brands.map((b) => `    ${JSON.stringify(b)},`),
    "  ],",
    "  lines: [",
    ...v.lines.map((l) => `    ${JSON.stringify(l)},`),
    "  ],",
    "};",
    "",
  ].join("\n");
  writeFileSync(OUT, body);
  console.log(`${OUT}: ${v.brands.length} brands, ${v.lines.length} lines`);
  await store.close();
}

main().catch((err: unknown) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
